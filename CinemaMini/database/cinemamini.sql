-- 1. Tài khoản và hồ sơ khách. ADMIN không cần hồ sơ Customer.
CREATE TABLE IF NOT EXISTS user_account (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email               varchar(254) NOT NULL UNIQUE,
    password_hash       varchar(255) NOT NULL,
    role                varchar(16) NOT NULL DEFAULT 'USER',
    active              boolean NOT NULL DEFAULT true,
    created_at          timestamptz NOT NULL DEFAULT clock_timestamp(),
    email_verified_at   timestamptz,
    CONSTRAINT ck_account_email_normalized CHECK (
        email = lower(btrim(email)) AND position('@' IN email) > 1
    ),
    CONSTRAINT ck_account_password CHECK (btrim(password_hash) <> ''),
    CONSTRAINT ck_account_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE IF NOT EXISTS customer (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      bigint NOT NULL UNIQUE,
    full_name       varchar(120) NOT NULL,
    customer_type   varchar(16) NOT NULL DEFAULT 'REGULAR',
    CONSTRAINT ck_customer_name CHECK (btrim(full_name) <> ''),
    CONSTRAINT ck_customer_type CHECK (
        customer_type IN ('REGULAR', 'STUDENT', 'MEMBER')
    )
);

-- 2. Một rạp CinemaMini, một Phòng 01: không cần bảng rạp/phòng riêng.
CREATE TABLE IF NOT EXISTS movie (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               varchar(200) NOT NULL UNIQUE,
    duration_minutes    smallint NOT NULL,
    description         text NOT NULL DEFAULT '',
    CONSTRAINT ck_movie_title CHECK (btrim(title) <> ''),
    CONSTRAINT ck_movie_duration CHECK (duration_minutes > 0)
);

CREATE TABLE IF NOT EXISTS seat (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            varchar(3) NOT NULL UNIQUE,
    row_label       char(1) NOT NULL,
    seat_number     smallint NOT NULL,
    seat_type       varchar(16) NOT NULL,
    CONSTRAINT uq_seat_position UNIQUE (row_label, seat_number),
    CONSTRAINT ck_seat_position CHECK (
        row_label IN ('A', 'B', 'C', 'D', 'E') AND seat_number BETWEEN 1 AND 6
    ),
    CONSTRAINT ck_seat_code CHECK (code = row_label || seat_number::text),
    CONSTRAINT ck_seat_type CHECK (
        (row_label IN ('A', 'B', 'C') AND seat_type = 'STANDARD')
        OR (row_label IN ('D', 'E') AND seat_type = 'VIP')
    )
);

CREATE TABLE IF NOT EXISTS showtime (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id            bigint NOT NULL,
    starts_at           timestamptz NOT NULL,
    ends_at             timestamptz NOT NULL,
    room_available_at   timestamptz NOT NULL,
    duration_minutes    smallint NOT NULL,
    cleanup_minutes     smallint NOT NULL DEFAULT 20,
    base_price          numeric(14,0) NOT NULL DEFAULT 80000,
    vip_surcharge       numeric(14,0) NOT NULL DEFAULT 20000,
    created_at          timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_showtime_movie_start UNIQUE (movie_id, starts_at),
    CONSTRAINT ck_showtime_prices CHECK (base_price > 0 AND vip_surcharge >= 0),
    CONSTRAINT ck_showtime_duration CHECK (
        duration_minutes > 0 AND cleanup_minutes >= 0
        AND extract(epoch FROM (ends_at - starts_at)) = duration_minutes * 60
        AND extract(epoch FROM (room_available_at - ends_at)) = cleanup_minutes * 60
    ),
    -- Một phòng: cấm chồng lấn cả phim lẫn thời gian dọn phòng.
    -- Khoảng [bắt đầu, phòng sẵn sàng) cho phép suất kế tiếp bắt đầu đúng mốc cuối.
    CONSTRAINT ex_showtime_room_overlap EXCLUDE USING gist (
        tstzrange(starts_at, room_available_at, '[)') WITH &&
    )
);

-- 3. Phiên giữ ghế có trước đơn; một phiên dùng một expires_at chung.
CREATE TABLE IF NOT EXISTS hold_session (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token           uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    customer_id     bigint NOT NULL,
    showtime_id     bigint NOT NULL,
    status          varchar(16) NOT NULL DEFAULT 'ACTIVE',
    started_at      timestamptz NOT NULL DEFAULT clock_timestamp(),
    expires_at      timestamptz NOT NULL,
    revision        bigint NOT NULL DEFAULT 0,
    CONSTRAINT ck_hold_status CHECK (
        status IN ('ACTIVE', 'CHECKOUT', 'CONSUMED', 'RELEASED', 'EXPIRED')
    ),
    CONSTRAINT ck_hold_deadline CHECK (
        expires_at > started_at AND expires_at <= started_at + interval '5 minutes'
    ),
    CONSTRAINT ck_hold_revision CHECK (revision >= 0)
);

CREATE TABLE IF NOT EXISTS booking (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                    varchar(40) NOT NULL UNIQUE,
    hold_id                 bigint NOT NULL UNIQUE,
    customer_id             bigint NOT NULL,
    showtime_id             bigint NOT NULL,
    status                  varchar(16) NOT NULL DEFAULT 'PENDING',
    contact_name            varchar(120) NOT NULL,
    contact_email           varchar(254) NOT NULL,
    contact_phone           varchar(30),
    note                    varchar(1000),
    seat_count              smallint NOT NULL,
    pricing_policy_snapshot varchar(16) NOT NULL,
    discount_percent        numeric(5,2) NOT NULL,
    subtotal                numeric(14,0) NOT NULL,
    discount_amount         numeric(14,0) NOT NULL,
    total                   numeric(14,0) NOT NULL,
    created_at              timestamptz NOT NULL DEFAULT clock_timestamp(),
    confirmed_at            timestamptz,
    cancelled_at            timestamptz,
    expired_at              timestamptz,
    CONSTRAINT ck_booking_code CHECK (btrim(code) <> ''),
    CONSTRAINT ck_booking_status CHECK (
        status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'EXPIRED')
    ),
    CONSTRAINT ck_booking_contact CHECK (
        btrim(contact_name) <> '' AND position('@' IN contact_email) > 1
    ),
    CONSTRAINT ck_booking_seat_count CHECK (seat_count BETWEEN 1 AND 6),
    CONSTRAINT ck_booking_policy CHECK (
        pricing_policy_snapshot IN ('REGULAR', 'STUDENT', 'MEMBER')
    ),
    -- Làm tròn HALF_UP cho tiền dương: tính total trước, discount = subtotal - total.
    CONSTRAINT ck_booking_price_snapshot CHECK (
        subtotal > 0 AND discount_percent >= 0 AND discount_percent < 100
        AND discount_amount >= 0 AND total > 0
        AND total = round(subtotal * (1 - discount_percent / 100), 0)
        AND discount_amount = subtotal - total
    )
);

CREATE TABLE IF NOT EXISTS booking_item (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id              bigint NOT NULL,
    seat_id                 bigint NOT NULL,
    seat_code_snapshot      varchar(3) NOT NULL,
    seat_type_snapshot      varchar(16) NOT NULL,
    base_price_snapshot     numeric(14,0) NOT NULL,
    vip_surcharge_snapshot  numeric(14,0) NOT NULL,
    unit_price_snapshot     numeric(14,0) NOT NULL,
    CONSTRAINT uq_booking_item_seat UNIQUE (booking_id, seat_id),
    CONSTRAINT ck_booking_item_seat_type CHECK (
        seat_type_snapshot IN ('STANDARD', 'VIP')
    ),
    CONSTRAINT ck_booking_item_price CHECK (
        base_price_snapshot > 0 AND vip_surcharge_snapshot >= 0
        AND unit_price_snapshot = base_price_snapshot + vip_surcharge_snapshot
        AND (seat_type_snapshot = 'VIP' OR vip_surcharge_snapshot = 0)
    )
    -- Không unique toàn cục theo suất-ghế: đơn đã hủy/hết hạn vẫn giữ lịch sử.
);

CREATE TABLE IF NOT EXISTS showtime_seat (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    showtime_id     bigint NOT NULL,
    seat_id         bigint NOT NULL,
    status          varchar(16) NOT NULL DEFAULT 'AVAILABLE',
    hold_id         bigint,
    booking_id      bigint,
    version         bigint NOT NULL DEFAULT 0,
    CONSTRAINT uq_showtime_seat UNIQUE (showtime_id, seat_id),
    -- Khi BOOKED, bỏ hold_id ở tồn ghế; booking.hold_id giữ liên kết phiên lịch sử.
    CONSTRAINT ck_showtime_seat_ownership CHECK (
        (status IN ('AVAILABLE', 'DISABLED') AND hold_id IS NULL AND booking_id IS NULL)
        OR (status = 'HELD' AND hold_id IS NOT NULL AND booking_id IS NULL)
        OR (status = 'BOOKED' AND hold_id IS NULL AND booking_id IS NOT NULL)
    ),
    CONSTRAINT ck_showtime_seat_version CHECK (version >= 0)
);

-- 4. Lịch sử tiền: thu dương, hoàn âm; không thay thế dòng thu gốc.
CREATE TABLE IF NOT EXISTS payment (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id              bigint NOT NULL,
    operation_type          varchar(16) NOT NULL,
    amount                  numeric(14,0) NOT NULL,
    currency                varchar(3) NOT NULL DEFAULT 'VND',
    payment_method          varchar(24) NOT NULL,
    status                  varchar(16) NOT NULL DEFAULT 'SUCCESS',
    original_payment_id     bigint UNIQUE,
    idempotency_key         varchar(128) NOT NULL,
    reference_code          varchar(100) NOT NULL UNIQUE,
    created_by              bigint NOT NULL,
    created_at              timestamptz NOT NULL DEFAULT clock_timestamp(),
    reason                  varchar(100) NOT NULL,
    CONSTRAINT uq_payment_booking_operation UNIQUE (booking_id, operation_type),
    CONSTRAINT uq_payment_actor_key UNIQUE (created_by, idempotency_key),
    CONSTRAINT ck_payment_currency CHECK (currency = 'VND'),
    CONSTRAINT ck_payment_status CHECK (status = 'SUCCESS'),
    CONSTRAINT ck_payment_method CHECK (
        payment_method IN (
            'CASH', 'BANK_TRANSFER', 'DOMESTIC_ATM', 'VISA',
            'MASTERCARD', 'MOMO', 'ZALOPAY', 'VNPAY'
        )
    ),
    CONSTRAINT ck_payment_operation_sign CHECK (
        (operation_type = 'PAYMENT' AND amount > 0 AND original_payment_id IS NULL)
        OR (operation_type = 'REFUND' AND amount < 0 AND original_payment_id IS NOT NULL)
    ),
    CONSTRAINT ck_payment_original CHECK (original_payment_id IS NULL OR original_payment_id <> id),
    CONSTRAINT ck_payment_keys CHECK (
        btrim(idempotency_key) <> '' AND btrim(reference_code) <> '' AND btrim(reason) <> ''
    )
);

-- Bảo vệ lịch sử append-only ngay trong database.
CREATE OR REPLACE FUNCTION reject_payment_history_change()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
    RAISE EXCEPTION 'Lịch sử payment chỉ được thêm dòng; không được sửa hoặc xóa.';
END;
$function$;

DO $trigger$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'public.payment'::regclass
          AND tgname = 'trg_payment_append_only'
          AND NOT tgisinternal
    ) THEN
        CREATE TRIGGER trg_payment_append_only
        BEFORE UPDATE OR DELETE ON payment
        FOR EACH ROW EXECUTE FUNCTION reject_payment_history_change();
    END IF;
END;
$trigger$;

-- 5. Chống request lặp và thông báo cho cả USER/ADMIN.
CREATE TABLE IF NOT EXISTS idempotency_request (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id            bigint NOT NULL,
    request_key         varchar(128) NOT NULL,
    operation_type      varchar(64) NOT NULL,
    payload_fingerprint varchar(64) NOT NULL,
    response_status     smallint,
    response_body       jsonb,
    reference_type      varchar(32),
    reference_id        bigint,
    created_at          timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_idempotency_actor_key UNIQUE (actor_id, request_key),
    CONSTRAINT ck_idempotency_values CHECK (
        btrim(request_key) <> '' AND btrim(operation_type) <> ''
        AND btrim(payload_fingerprint) <> ''
    ),
    CONSTRAINT ck_idempotency_response CHECK (response_status BETWEEN 100 AND 599)
);

CREATE TABLE IF NOT EXISTS notification (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id    bigint NOT NULL,
    event_id        uuid NOT NULL,
    type            varchar(32) NOT NULL,
    content         text NOT NULL,
    booking_id      bigint NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT clock_timestamp(),
    read_at         timestamptz,
    CONSTRAINT uq_notification_recipient_event UNIQUE (recipient_id, event_id),
    CONSTRAINT ck_notification_type CHECK (
        type IN ('BOOKING_CONFIRMED', 'BOOKING_CANCELLED', 'BOOKING_EXPIRED')
    ),
    CONSTRAINT ck_notification_content CHECK (btrim(content) <> ''),
    CONSTRAINT ck_notification_read_at CHECK (read_at IS NULL OR read_at >= created_at)
);

-- PRIMARY KEY, UNIQUE, CHECK và index chỉ áp dụng trong từng bảng.
-- Index cho lịch chiếu, worker hết hạn, lịch sử đơn và bảng thông báo.
CREATE INDEX IF NOT EXISTS idx_showtime_starts_at ON showtime (starts_at);
CREATE INDEX IF NOT EXISTS idx_hold_expiration ON hold_session (status, expires_at)
    WHERE status IN ('ACTIVE', 'CHECKOUT');
CREATE INDEX IF NOT EXISTS idx_hold_customer ON hold_session (customer_id, started_at DESC);
CREATE INDEX IF NOT EXISTS idx_booking_customer ON booking (customer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_booking_showtime ON booking (showtime_id, status);
CREATE INDEX IF NOT EXISTS idx_booking_item_seat ON booking_item (seat_id);
CREATE INDEX IF NOT EXISTS idx_showtime_seat_hold ON showtime_seat (hold_id)
    WHERE hold_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_showtime_seat_booking ON showtime_seat (booking_id)
    WHERE booking_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_payment_created_at ON payment (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notification_recipient ON notification (recipient_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notification_unread ON notification (recipient_id)
    WHERE read_at IS NULL;

