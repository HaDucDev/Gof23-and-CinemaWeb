BEGIN;
SET LOCAL TIME ZONE 'Asia/Ho_Chi_Minh';
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
CREATE SCHEMA IF NOT EXISTS account;
CREATE SCHEMA IF NOT EXISTS booking;
CREATE SCHEMA IF NOT EXISTS seat;
CREATE SCHEMA IF NOT EXISTS payment;
REVOKE ALL ON SCHEMA account, booking, seat, payment FROM PUBLIC;

CREATE TABLE IF NOT EXISTS account.user_accounts (
    account_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    role varchar(16) NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN')),
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    email_verified_at timestamptz,
    CHECK (email = lower(btrim(email)) AND position('@' IN email) > 1),
    CHECK (btrim(password_hash) <> '')
);
CREATE TABLE IF NOT EXISTS account.customers (
    customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL UNIQUE,
    full_name varchar(120) NOT NULL CHECK (btrim(full_name) <> ''),
    customer_type varchar(16) NOT NULL DEFAULT 'REGULAR'
        CHECK (customer_type IN ('REGULAR', 'STUDENT', 'MEMBER'))
);

CREATE TABLE IF NOT EXISTS seat.movies (
    movie_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(200) NOT NULL UNIQUE CHECK (btrim(title) <> ''),
    duration_minutes smallint NOT NULL CHECK (duration_minutes > 0),
    description text NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS seat.seats (
    seat_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seat_no varchar(3) NOT NULL UNIQUE,
    row_label char(1) NOT NULL,
    seat_number smallint NOT NULL,
    seat_type varchar(16) NOT NULL,
    UNIQUE (row_label, seat_number),
    CHECK (row_label IN ('A', 'B', 'C', 'D', 'E') AND seat_number BETWEEN 1 AND 6),
    CHECK (seat_no = row_label || seat_number::text),
    CHECK ((row_label IN ('A', 'B', 'C') AND seat_type = 'STANDARD')
        OR (row_label IN ('D', 'E') AND seat_type = 'VIP'))
);
CREATE TABLE IF NOT EXISTS seat.showtimes (
    showtime_id varchar(40) PRIMARY KEY,
    movie_id bigint NOT NULL,
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    room_available_at timestamptz NOT NULL,
    duration_minutes smallint NOT NULL,
    cleanup_minutes smallint NOT NULL DEFAULT 20,
    base_price numeric(14,0) NOT NULL DEFAULT 80000,
    vip_surcharge numeric(14,0) NOT NULL DEFAULT 20000,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (movie_id, starts_at),
    CHECK (base_price > 0 AND vip_surcharge >= 0),
    CHECK (duration_minutes > 0 AND cleanup_minutes >= 0
        AND extract(epoch FROM (ends_at - starts_at)) = duration_minutes * 60
        AND extract(epoch FROM (room_available_at - ends_at)) = cleanup_minutes * 60),
    EXCLUDE USING gist (tstzrange(starts_at, room_available_at, '[)') WITH &&)
);
CREATE TABLE IF NOT EXISTS seat.showtime_seats (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    showtime_id varchar(40) NOT NULL,
    seat_id bigint NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'AVAILABLE',
    held_by_booking_id uuid,
    held_by_hold_id uuid,
    hold_expires_at timestamptz,
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0),
    UNIQUE (showtime_id, seat_id),
    CHECK ((status IN ('AVAILABLE', 'DISABLED') AND held_by_hold_id IS NULL AND held_by_booking_id IS NULL AND hold_expires_at IS NULL)
        OR (status = 'HELD' AND held_by_hold_id IS NOT NULL AND hold_expires_at IS NOT NULL)
        OR (status = 'SOLD' AND held_by_hold_id IS NOT NULL AND held_by_booking_id IS NOT NULL AND hold_expires_at IS NULL))
);
CREATE TABLE IF NOT EXISTS seat.seat_holds (
    hold_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    booking_id uuid UNIQUE,
    account_id bigint,
    showtime_id varchar(40) NOT NULL,
    token_hash varchar(64) NOT NULL,
    seat_count smallint NOT NULL CHECK (seat_count BETWEEN 1 AND 6),
    revision bigint NOT NULL DEFAULT 0 CHECK (revision >= 0),
    status varchar(32) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN
        ('ACTIVE','CHECKOUT','PAYMENT_PROCESSING','CONSUMED','RELEASED','EXPIRED')),
    started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    expires_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (expires_at > started_at AND expires_at <= started_at + interval '5 minutes')
);
CREATE TABLE IF NOT EXISTS seat.hold_operations (
    operation_key varchar(128) PRIMARY KEY,
    account_id bigint NOT NULL,
    request_hash varchar(64) NOT NULL,
    hold_id uuid NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE IF NOT EXISTS booking.bookings (
    booking_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    idempotency_key varchar(128) NOT NULL UNIQUE,
    request_hash varchar(64) NOT NULL,
    account_id bigint,
    customer_id bigint,
    showtime_id varchar(40) NOT NULL,
    hold_id uuid NOT NULL UNIQUE,
    hold_revision bigint NOT NULL DEFAULT 0,
    status varchar(32) NOT NULL DEFAULT 'CREATING' CHECK (status IN
        ('CREATING','PENDING','PAYMENT_PROCESSING','COMPENSATING','CANCELLING','CONFIRMED','CANCELLED','EXPIRED')),
    amount numeric(14,0) NOT NULL CHECK (amount > 0),
    subtotal numeric(14,0) NOT NULL CHECK (subtotal > 0),
    discount_percent smallint NOT NULL CHECK (discount_percent IN (0,10,15)),
    customer_type varchar(16) NOT NULL CHECK (customer_type IN ('REGULAR','STUDENT','MEMBER')),
    movie_title varchar(200) NOT NULL,
    starts_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    ticket_code varchar(64) UNIQUE,
    payment_id uuid,
    payment_method varchar(24),
    operation_id uuid,
    contact_name varchar(120) NOT NULL,
    contact_email varchar(254) NOT NULL,
    contact_phone varchar(30) NOT NULL,
    note varchar(1000),
    failure_reason text,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (btrim(idempotency_key) <> '' AND btrim(request_hash) <> ''),
    CHECK (status <> 'CONFIRMED' OR ticket_code IS NOT NULL)
);
CREATE TABLE IF NOT EXISTS booking.booking_items (
    item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id uuid NOT NULL,
    seat_id bigint NOT NULL,
    seat_no_snapshot varchar(3) NOT NULL,
    seat_type_snapshot varchar(16) NOT NULL CHECK (seat_type_snapshot IN ('STANDARD', 'VIP')),
    base_price_snapshot numeric(14,0) NOT NULL,
    vip_surcharge_snapshot numeric(14,0) NOT NULL DEFAULT 0,
    unit_price_snapshot numeric(14,0) NOT NULL,
    CHECK (base_price_snapshot > 0 AND vip_surcharge_snapshot >= 0
        AND unit_price_snapshot = base_price_snapshot + vip_surcharge_snapshot),
    CHECK (seat_type_snapshot = 'VIP' OR vip_surcharge_snapshot = 0),
    UNIQUE (booking_id,seat_id)
);
CREATE TABLE IF NOT EXISTS booking.idempotency_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key varchar(128) NOT NULL UNIQUE,
    operation_type varchar(64) NOT NULL,
    payload_fingerprint varchar(64) NOT NULL,
    account_id bigint,
    booking_id uuid,
    response_status smallint CHECK (response_status BETWEEN 100 AND 599),
    response_body jsonb,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (btrim(request_key) <> '' AND btrim(operation_type) <> '' AND btrim(payload_fingerprint) <> '')
);
CREATE TABLE IF NOT EXISTS booking.notifications (
    notification_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_account_id bigint NOT NULL,
    event_id uuid NOT NULL,
    booking_id uuid NOT NULL,
    type varchar(32) NOT NULL CHECK (type IN ('BOOKING_CONFIRMED', 'BOOKING_CANCELLED', 'BOOKING_EXPIRED')),
    content text NOT NULL CHECK (btrim(content) <> ''),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    read_at timestamptz,
    UNIQUE (recipient_account_id, event_id),
    CHECK (read_at IS NULL OR read_at >= created_at)
);
CREATE TABLE IF NOT EXISTS booking.booking_timeline (
    timeline_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id uuid NOT NULL,
    service_name varchar(64) NOT NULL,
    action varchar(100) NOT NULL,
    result varchar(32) NOT NULL,
    happened_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    detail jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE IF NOT EXISTS payment.payments (
    payment_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    booking_id uuid NOT NULL UNIQUE,
    amount numeric(14,0) NOT NULL CHECK (amount > 0),
    status varchar(32) NOT NULL DEFAULT 'INIT'
        CHECK (status IN ('INIT', 'SUCCEEDED', 'FAILED', 'REFUNDED')),
    idempotency_key varchar(128) NOT NULL UNIQUE CHECK (btrim(idempotency_key) <> ''),
    request_hash varchar(64) NOT NULL,
    payment_method varchar(24) NOT NULL CHECK (payment_method IN ('CASH','BANK_TRANSFER','DOMESTIC_ATM','VISA','MASTERCARD','MOMO','ZALOPAY','VNPAY')),
    simulated_outcome varchar(16) NOT NULL CHECK (simulated_outcome IN ('SUCCESS','FAIL')),
    failure_reason text,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE IF NOT EXISTS payment.payment_transactions (
    transaction_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    payment_id uuid NOT NULL,
    booking_id uuid NOT NULL,
    operation_type varchar(16) NOT NULL,
    amount numeric(14,0) NOT NULL,
    currency varchar(3) NOT NULL DEFAULT 'VND' CHECK (currency = 'VND'),
    payment_method varchar(24) NOT NULL
        CHECK (payment_method IN ('CASH', 'BANK_TRANSFER', 'DOMESTIC_ATM',
                                  'VISA', 'MASTERCARD', 'MOMO', 'ZALOPAY', 'VNPAY')),
    original_transaction_id uuid UNIQUE,
    idempotency_key varchar(128) NOT NULL UNIQUE CHECK (btrim(idempotency_key) <> ''),
    reference_code varchar(100) NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    reason varchar(100) NOT NULL,
    UNIQUE (payment_id, operation_type),
    CHECK ((operation_type = 'PAYMENT' AND amount > 0 AND original_transaction_id IS NULL)
        OR (operation_type = 'REFUND' AND amount < 0 AND original_transaction_id IS NOT NULL)),
    CHECK (original_transaction_id IS NULL OR original_transaction_id <> transaction_id),
    CHECK (btrim(reference_code) <> '' AND btrim(reason) <> '')
);
CREATE OR REPLACE FUNCTION payment.reject_history_change() RETURNS trigger
LANGUAGE plpgsql AS $function$
BEGIN
    RAISE EXCEPTION 'Payment history is append-only; UPDATE and DELETE are forbidden.';
END;
$function$;
DO $trigger$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'payment.payment_transactions'::regclass
          AND tgname = 'trg_payment_history_append_only' AND NOT tgisinternal) THEN
        CREATE TRIGGER trg_payment_history_append_only
        BEFORE UPDATE OR DELETE ON payment.payment_transactions
        FOR EACH ROW EXECUTE FUNCTION payment.reject_history_change();
    END IF;
END;
$trigger$;

